#!/usr/bin/env python3
"""Index *file metadata* from two user-selected Internet Archive collections.

No game content is fetched while indexing. Listing presence is not evidence of
an accessible download, accuracy, or permission to reproduce the item.
Run in CI before compiling RetroVerse. The C app only accepts the exact
manifest IDs created here; clients cannot submit arbitrary download URLs.
"""
import hashlib
import json
import re
from pathlib import Path
from urllib.parse import quote
from urllib.request import Request, urlopen

HERE=Path(__file__).resolve().parent
OUTPUT=HERE/"archive_sources.inc"
SOURCES={
    "PS1":("Centuron-PSX","",(".bin",".cue")),
    "GC":("gamecubegames","Nintendo GameCube/",(".iso",".gcm")),
}
MAX_FILE_BYTES=10*1024**3
MAX_ROWS=12000

def group_name(name):
    stem=name.rsplit(".",1)[0]
    # A cue file may refer to multiple "Game (Track 01).bin" files.
    stem=re.sub(r"(?i)\s*\(track[ _-]*0*\d+\)$","",stem)
    stem=re.sub(r"(?i)[ ._-]+track[ _-]*0*\d+$","",stem)
    return stem.strip(" ._").casefold()

def safe_filename(name):
    return (1<=len(name.encode("utf-8"))<=210 and
            name not in (".","..") and not name.startswith(".") and
            not any(ord(c)<32 or c in '/\\:<>|"?*' for c in name))

def collect(platform, item, prefix, extensions):
    url="https://archive.org/metadata/"+quote(item,safe="")
    with urlopen(Request(url,headers={"User-Agent":"RetroVerse-PS5-Indexer/1.1",
                                    "Accept":"application/json"}),timeout=90) as resp:
        if resp.status!=200:
            raise RuntimeError(f"{item} returned HTTP {resp.status}")
        metadata=json.load(resp)
    files=metadata.get("files",[])
    if not isinstance(files,list):raise RuntimeError(f"{item} metadata has no file list")
    selected=[]
    for f in files:
        full=f.get("name","")
        if not full.startswith(prefix):continue
        rest=full[len(prefix):]
        if "/" in rest or not safe_filename(rest):continue
        if not rest.lower().endswith(extensions):continue
        try:size=int(f.get("size",0))
        except (ValueError,TypeError):continue
        if not (0<size<=MAX_FILE_BYTES):continue
        checksum=str(f.get("md5","")).lower()
        if not re.fullmatch(r"[0-9a-f]{32}",checksum):checksum=""
        sha1=str(f.get("sha1","")).lower()
        if not re.fullmatch(r"[0-9a-f]{40}",sha1):sha1=""
        ident=hashlib.sha256((platform+"\0"+full).encode()).hexdigest()[:20]
        selected.append({
            "platform":platform,
            "title":rest.rsplit(".",1)[0],
            "name":rest,
            "path":"archive/"+platform+"/"+ident,
            "url":"https://archive.org/download/"+quote(item,safe="")+"/"+quote(full,safe="/"),
            "size":size,
            "md5":checksum,
            "sha1":sha1,
            "group":group_name(rest),
            "source_page":"https://archive.org/download/"+quote(item,safe="")+"/"+quote(prefix,safe="/"),
        })
    selected.sort(key=lambda r:r["name"].casefold())
    print(f"Archive index {item}/{prefix}: {len(selected)} entries from {len(files)} metadata files",flush=True)
    if not selected:
        raise RuntimeError(f"Empty {platform} archive index; refusing to publish empty source")
    return selected

def generate(rows):
    lines=[
        "/* GENERATED by archive_source_build.py; filenames and URLs from Archive metadata. */",
        "/* Metadata is NOT proof of accessibility, license, or file integrity. */",
        "typedef struct {",
        " const char *platform, *title, *filename, *path, *url, *md5, *sha1, *group, *source_page;",
        " unsigned long long size;",
        "} archive_source_t;",
        "static const archive_source_t archive_sources[]={",
    ]
    for r in rows:
        keys=("platform","title","name","path","url","md5","sha1","group","source_page")
        parts=[json.dumps(r[k],ensure_ascii=True) for k in keys]
        parts.append(str(r["size"])+"ULL")
        lines.append(" {"+", ".join(parts)+"},")
    lines+=["};","static const size_t archive_sources_count=sizeof archive_sources/sizeof archive_sources[0];"]
    OUTPUT.write_text("\n".join(lines)+"\n",encoding="utf-8")
    print("Generated",OUTPUT.name,len(rows),"file listings, bytes",OUTPUT.stat().st_size,flush=True)

def main():
    rows=[]
    for platform,(item,prefix,exts) in SOURCES.items():
        rows.extend(collect(platform,item,prefix,exts))
        if len(rows)>MAX_ROWS:raise RuntimeError("Too many archive file entries")
    generate(rows)

if __name__=="__main__":main()
