#!/usr/bin/env python3
"""Build-time index snapshot for RetroVerse PS5.
Downloads Libretro public thumbnail indexes on CI, not on the console.
Output: a generated C include with system-index HTML for the current build.
"""
import html
from html.parser import HTMLParser
import os
from pathlib import Path
import time
from urllib.parse import quote, unquote, urljoin
from urllib.request import Request, urlopen

SYSTEMS = {
    "SNES": "Nintendo - Super Nintendo Entertainment System",
    "NES": "Nintendo - Nintendo Entertainment System",
    "GENESIS": "Sega - Mega Drive - Genesis",
    "GB": "Nintendo - Game Boy",
    "GBA": "Nintendo - Game Boy Advance",
    "N64": "Nintendo - Nintendo 64",
    "GC": "Nintendo - GameCube",
    "PS1": "Sony - PlayStation",
    "PS2": "Sony - PlayStation 2",
    "DC": "Sega - Dreamcast",
    "ARCADE": "MAME",
}

class Anchors(HTMLParser):
    def __init__(self):
        super().__init__()
        self.filenames = set()
    def handle_starttag(self, tag, attrs):
        if tag.lower() != "a":
            return
        d=dict(attrs)
        href=d.get("href","")
        filename=unquote(href.rsplit("/",1)[-1])
        if filename.lower().endswith(".png") and len(filename)<256 and filename and not filename.startswith("."):
            self.filenames.add(filename)

def fetch(platform, system):
    url="https://thumbnails.libretro.com/"+quote(system,safe="")+"/Named_Boxarts/"
    last_error=None
    for attempt in range(3):
        try:
            req=Request(url,headers={"User-Agent":"RetroVerse-PS5-catalog-builder/0.3"})
            with urlopen(req,timeout=40) as resp:
                raw=resp.read(20*1024*1024+1)
                if len(raw)>20*1024*1024: raise RuntimeError("Index HTML unexpectedly large")
                page=raw.decode("utf-8","replace")
            parser=Anchors()
            parser.feed(page)
            names=sorted(parser.filenames,key=str.casefold)
            if len(names)<10: raise RuntimeError(f"Unexpectedly small index: {len(names)} entries")
            print(f"{platform}: {len(names)} thumbnail entries, {len(raw)} raw bytes")
            return names
        except Exception as exc:
            last_error=exc
            print(f"{platform} attempt {attempt+1} failed: {exc}", flush=True)
            time.sleep(attempt+1)
    raise RuntimeError(f"Unable to fetch {platform} artwork index: {last_error}")

def c_string(text):
    # ASCII-only escaped C literal; hex data avoids runtime font/encoding assumptions.
    raw=text.encode("utf-8")
    pieces=[]
    for i in range(0,len(raw),64):
        chunk=raw[i:i+64]
        pieces.append('    "'+"".join("\\x%02x"%v for v in chunk)+'"')
    return "\n".join(pieces)

def main():
    lines=["/* AUTO-GENERATED by catalog_build.py; NOT hand-edited. */",
           "typedef struct { const char *platform; const char *html; size_t length; } embedded_catalog_t;"]
    entries=[]
    for platform, system in SYSTEMS.items():
        names=fetch(platform,system)
        # Keep exact file names (and suffix); the front-end strips .png and parses href.
        document="<html><body>"+ "".join(
            '<a href="'+html.escape(quote(name,safe=""),quote=True)+'"></a>'
            for name in names
        )+"</body></html>"
        ident="catalog_"+platform
        lines.append("static const char "+ident+"[] =\n"+c_string(document)+";")
        entries.append(f'    {{"{platform}", {ident}, sizeof({ident})-1}},')
    lines.append("static const embedded_catalog_t embedded_catalogs[] = {")
    lines.extend(entries)
    lines.append("};")
    path=Path(__file__).with_name("catalog_data.inc")
    path.write_text("\n".join(lines)+"\n",encoding="utf-8")
    print("Wrote",path,"bytes",path.stat().st_size)

if __name__=="__main__":main()
