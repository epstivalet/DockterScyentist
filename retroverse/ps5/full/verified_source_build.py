#!/usr/bin/env python3
"""Generate a deterministic C catalog from explicitly approved developer releases.

No Archive scraping, arbitrary URLs, or guessed direct-file paths.
All playable files have pinned size and SHA-256. See verify_sources.py for CI checks.
"""
from pathlib import Path
import json
import re

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "verified_sources.json"
OUTPUT = HERE / "verified_sources.inc"
PLATFORMS = {"SNES", "NES", "GENESIS", "GB", "GBA", "N64", "GC",
             "PS1", "PS2", "DC", "ARCADE"}
ALLOWED_EXT = {".zip", ".7z", ".nes", ".sfc", ".smc", ".gb", ".gbc", ".gba",
               ".n64", ".z64", ".v64", ".md", ".gen", ".bin", ".cue", ".iso",
               ".chd", ".cso", ".pbp", ".gdi", ".cdi", ".m3u", ".nds", ".rom",
               ".pce", ".wad", ".rvz", ".gcm"}
def validated():
    doc = json.loads(SOURCE.read_text(encoding="utf-8"))
    assert doc["schema_version"] == 1
    rows = doc["sources"]
    assert rows, "No approved homebrew sources"
    seen = set()
    for row in rows:
        assert set(row) == {"platform", "title", "filename", "path", "url",
                            "sha256", "size", "provider", "license", "source_page"}
        platform, name = row["platform"], row["filename"]
        assert platform in PLATFORMS
        assert 1 <= len(name) <= 200 and not any(c in name for c in '/\\:?&#%')
        assert not name.startswith(".") and ".." not in name
        assert Path(name).suffix.lower() in ALLOWED_EXT
        assert row["path"] == f"verified/{platform}/{name}"
        assert row["path"] not in seen
        seen.add(row["path"])
        assert re.fullmatch(r"[0-9a-f]{64}", row["sha256"])
        assert 1 <= row["size"] <= 10 * 1024**3
        assert row["url"].startswith("https://github.com/")
        assert "/releases/download/" in row["url"]
        assert row["url"].endswith("/" + name)
        assert row["source_page"].startswith("https://github.com/")
        assert 1 <= len(row["title"]) < 200
        assert row["provider"] and row["license"]
    return rows

def main():
    lines = [
        "/* GENERATED by verified_source_build.py; edit verified_sources.json instead. */",
        "typedef struct {",
        " const char *platform, *title, *filename, *path, *url, *sha256;",
        " unsigned long long size;",
        " const char *provider, *license, *source_page;",
        "} verified_source_t;",
        "static const verified_source_t verified_sources[] = {",
    ]
    for row in validated():
        keys = ("platform", "title", "filename", "path", "url", "sha256")
        after = ("provider", "license", "source_page")
        parts = [json.dumps(row[key], ensure_ascii=True) for key in keys]
        parts.append(str(row["size"]) + "ULL")
        parts += [json.dumps(row[key], ensure_ascii=True) for key in after]
        lines.append(" {" + ", ".join(parts) + "},")
    lines += ["};", "static const size_t verified_sources_count =",
              "    sizeof verified_sources / sizeof verified_sources[0];"]
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Approved downloadable homebrew files:", len(validated()))

if __name__ == "__main__":
    main()
